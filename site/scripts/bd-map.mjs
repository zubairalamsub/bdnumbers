// Builds the weather map's outlines from geoBoundaries' simplified GeoJSON:
// - src/lib/bd-map.ts: the 8 divisions and the projection, from ADM1 (CC0 1.0, public domain)
//   https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/BGD/ADM1/geoBoundaries-BGD-ADM1_simplified.geojson
// - src/lib/bd-districts.ts: the 64 districts, from ADM2 (Bangladesh Bureau of Statistics and OCHA ROAP,
//   CC BY 3.0 IGO: the map credits them)
//   https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/BGD/ADM2/geoBoundaries-BGD-ADM2_simplified.geojson
//
//   node scripts/bd-map.mjs <ADM1 file> <ADM2 file>
//
// Projection: equirectangular, x scaled by cos(middle latitude) so the shape isn't stretched; 300 units
// wide. The district file uses the division file's projection, so the two line up.
import fs from 'node:fs';

const WIDTH = 300;
const PAD = 4;
/** Douglas–Peucker tolerance (divisions, districts) and smallest island kept, in map units (1 unit ≈ 1.6 km). */
const TOLERANCE = 0.3;
const DISTRICT_TOLERANCE = 0.45;
const MIN_AREA = 1;
/** geoBoundaries shapeName → our city/division id (the source spells Rajshahi "Rajshani"). */
const IDS = {
  Barisal: 'barishal',
  Chittagong: 'chattogram',
  Dhaka: 'dhaka',
  Khulna: 'khulna',
  Mymensingh: 'mymensingh',
  Rajshani: 'rajshahi',
  Rajshahi: 'rajshahi',
  Rangpur: 'rangpur',
  Sylhet: 'sylhet',
};
/** geoBoundaries ADM2 names that differ from our district ids (older spellings). */
const DISTRICT_IDS = {
  Barisal: 'barishal',
  Bogra: 'bogura',
  Brahamanbaria: 'brahmanbaria',
  Chittagong: 'chattogram',
  Comilla: 'cumilla',
  "Cox's Bazar": 'coxs-bazar',
  Jessore: 'jashore',
  Maulvibazar: 'moulvibazar',
  Nawabganj: 'chapainawabganj',
  Netrakona: 'netrokona',
};

const geo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const polygons = (g) => (g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates]);
const all = geo.features.flatMap((f) => polygons(f.geometry).flat(2));
const lons = all.map((p) => p[0]);
const lats = all.map((p) => p[1]);
const lonMin = Math.min(...lons);
const lonMax = Math.max(...lons);
const latMin = Math.min(...lats);
const latMax = Math.max(...lats);
const cos = Math.cos((((latMin + latMax) / 2) * Math.PI) / 180);
const k = (WIDTH - 2 * PAD) / ((lonMax - lonMin) * cos);
const height = Math.ceil((latMax - latMin) * k + 2 * PAD);
const project = ([lon, lat]) => [PAD + (lon - lonMin) * cos * k, PAD + (latMax - lat) * k];

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [a, b] = [points[0], points.at(-1)];
  let max = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    const d = Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / len;
    if (d > max) [max, index] = [d, i];
  }
  if (max <= tolerance) return [a, b];
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)];
}

/** A closed ring starts and ends on the same point, which Douglas–Peucker can't use as its baseline: split it at its farthest point. */
function simplifyRing(ring, tolerance) {
  const far = ring.reduce((best, p, i) => (Math.hypot(p[0] - ring[0][0], p[1] - ring[0][1]) > Math.hypot(ring[best][0] - ring[0][0], ring[best][1] - ring[0][1]) ? i : best), 0);
  return [...simplify(ring.slice(0, far + 1), tolerance).slice(0, -1), ...simplify(ring.slice(far), tolerance)];
}

const area = (ring) => Math.abs(ring.reduce((s, [x, y], i) => s + x * ring[(i + 1) % ring.length][1] - ring[(i + 1) % ring.length][0] * y, 0)) / 2;
const fmt = (n) => String(Math.round(n * 10) / 10);

/** SVG path data for one feature's polygons, simplified, without slivers. */
function pathData(geometry, tolerance) {
  return polygons(geometry)
    .flatMap((poly) => poly.map((ring) => simplifyRing(ring.map(project), tolerance)))
    .filter((ring) => ring.length >= 4 && area(ring) >= MIN_AREA)
    .map((ring) => `M${ring.slice(0, -1).map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join('L')}Z`)
    .join('');
}

const outlines = (features, idFor, tolerance) =>
  features
    .map((f) => {
      const id = idFor(f.properties.shapeName);
      if (!id) throw new Error(`unknown area ${f.properties.shapeName}`);
      return { id, d: pathData(f.geometry, tolerance) };
    })
    .sort((a, b) => a.id.localeCompare(b.id));

const divisions = outlines(geo.features, (name) => IDS[name], TOLERANCE);
const districtGeo = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
const districts = outlines(districtGeo.features, (name) => DISTRICT_IDS[name] ?? name.toLowerCase(), DISTRICT_TOLERANCE);
if (districts.length !== 64) throw new Error(`expected 64 districts, got ${districts.length}`);

fs.writeFileSync(
  new URL('../src/lib/bd-map.ts', import.meta.url),
  `// Generated by scripts/bd-map.mjs from geoBoundaries BGD ADM1 (simplified), CC0 1.0. Don't edit by hand.

export const BD_MAP = {
  width: ${WIDTH},
  height: ${height},
  divisions: ${JSON.stringify(divisions, null, 2).replace(/\n/g, '\n  ')},
} as const;

/** Map units for a latitude/longitude, in the same projection as the outlines. */
export function bdProject(lat: number, lon: number): [x: number, y: number] {
  return [${PAD} + (lon - ${lonMin}) * ${cos} * ${k}, ${PAD} + (${latMax} - lat) * ${k}];
}
`,
);
fs.writeFileSync(
  new URL('../src/lib/bd-districts.ts', import.meta.url),
  `// Generated by scripts/bd-map.mjs from geoBoundaries BGD ADM2 (simplified): Bangladesh Bureau of Statistics
// and OCHA ROAP, CC BY 3.0 IGO. Same projection as bd-map.ts. Loaded only when the weather map is zoomed in.
// Don't edit by hand.

export const BD_DISTRICTS: ReadonlyArray<{ id: string; d: string }> = ${JSON.stringify(districts)};
`,
);
console.log(`divisions ${divisions.length}, districts ${districts.length}`);
